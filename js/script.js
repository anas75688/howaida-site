// Normalise a product object so all downstream rendering works
// regardless of whether the CMS saved desc_ar or description_ar, etc.
function normaliseProduct(p) {
    if (!p) return p;
    // Description aliases
    p.description_ar = p.description_ar || p.desc_ar || p.description || '';
    p.description_tr = p.description_tr || p.desc_tr || p.description || '';
    p.description_en = p.description_en || p.desc_en || p.description || '';
    // Image aliases - prefer images[] array, fall back to single image field
    if (!p.images || !Array.isArray(p.images) || p.images.length === 0) {
        p.images = p.image ? [p.image] : [];
    }
    // Strip any accidental local file:/// paths from image URLs
    p.images = p.images.filter(src => src && !src.startsWith('C:\\') && !src.startsWith('file:///'));
    return p;
}

// Fetch API Layer - 4-tier chain for robustness
// Tier 0: Live Production API (Real-time, if configured)
// Tier 1: /data/catalog.json  (committed to repo for Netlify)
// Tier 2: localStorage 'products' (admin additions on this device)
// Tier 3: empty array (graceful fallback)
/**
 * Unified Data Fetching System
 * Ensures a Single Source of Truth for all dynamic content.
 */
async function fetchFromSource(category, normalizer = (x) => x) {
    let items = [];
    const cacheKey = `howayda_${category}`;

    // --- Tier 1: Backend API (Single Source of Truth) ---
    try {
        if (window.SyncEngine) {
            console.log(`🌐 Fetching live ${category} from API/GitHub...`);
            items = await window.SyncEngine.fetchItems(category);
            if (items && items.length > 0) {
                console.log(`✅ Loaded ${category} from source:`, items.length);
                localStorage.setItem(cacheKey, JSON.stringify(items)); // Update cache
                return items.map(normalizer).filter(Boolean);
            }
        }
    } catch (err) {
        console.warn(`${category} source fetch failed:`, err.message);
    }

    // --- Tier 2: Local Storage (Cache fallback) ---
    try {
        const localData = localStorage.getItem(cacheKey);
        if (localData) {
            items = JSON.parse(localData);
            if (items.length > 0) {
                console.log(`📦 Loaded ${category} from cache:`, items.length);
                return items.map(normalizer).filter(Boolean);
            }
        }
    } catch (err) {
        console.error(`Error reading ${category} cache:`, err);
    }

    return [];
}

async function fetchProductsFromCMS() {
    return await fetchFromSource('products', normaliseProduct);
}

