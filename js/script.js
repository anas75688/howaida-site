function updateMetaKeywords(keywords) {
    let metaTag = document.querySelector('meta[name="keywords"]');
    if (!metaTag) {
        metaTag = document.createElement('meta');
        metaTag.name = "keywords";
        document.head.appendChild(metaTag);
    }
    if (keywords) {
        if (Array.isArray(keywords)) {
            metaTag.content = keywords.join(', ');
        } else {
            metaTag.content = keywords;
        }
    } else {
        metaTag.content = "عبايات, حجابات, أزياء محتشمة, Howayda, Abaya, Hijab, Modest Fashion";
    }
}

window.openProductModal = function(productOrId) {
    // Accept either a full product object (new panel) or an ID string (legacy modal)
    let product;
    if (productOrId && typeof productOrId === 'object') {
        product = productOrId;
    } else {
        product = (globalProducts || []).find(p => p && p.id === productOrId) ||
                  (globalFeatured || []).find(p => p && (p.product_id || p.id) === productOrId);
    }
    if (!product) return;

    const lang = localStorage.getItem('preferredLang') || 'ar';
    const t = translations[lang] || translations['ar'];

    // Update SEO keywords
    updateMetaKeywords(product.seo_keywords || product.meta_keywords);

    // If new panel exists (products.html), delegate to it
    if (typeof openPanel === 'function') {
        openPanel(product);
        return;
    }

    // Legacy modal fallback (index.html)
    let nameAr = product.name_ar || product.title_ar || product.name || '';
    let nameTr = product.name_tr || product.title_tr || product.name || '';
    let nameEn = product.name_en || product.title_en || product.name || nameTr || nameAr;
    let name = lang === 'ar' ? nameAr : (lang === 'tr' ? nameTr : nameEn);
    if (!name) name = lang === 'ar' ? 'منتج غير مسمى' : (lang === 'tr' ? 'İsimsiz ürün' : 'Unnamed Product');

    let descAr = product.description_ar || product.short_desc_ar || product.description || '';
    let descTr = product.description_tr || product.short_desc_tr || product.description || '';
    let descEn = product.description_en || product.short_desc_en || product.description || descTr || descAr;
    let desc = lang === 'ar' ? descAr : (lang === 'tr' ? descTr : descEn);
    if (!desc) desc = lang === 'ar' ? 'لا يوجد وصف متاح.' : (lang === 'tr' ? 'Açıklama bulunmuyor.' : 'No description available.');
    
    let price = product.price ? product.price : '';

    const titleEl = document.getElementById('modal-title');
    const descEl = document.getElementById('modal-desc');
    if (titleEl) titleEl.textContent = name;
    if (descEl) descEl.textContent = desc;
    
    const priceEl = document.getElementById('modal-price');
    if (priceEl) priceEl.textContent = price;
    
    const availBadge = document.getElementById('modal-availability');
    if (availBadge) {
        if (product.availability === 'In stock' || !product.availability) {
            availBadge.className = 'badge badge-instock';
            availBadge.textContent = t.inStock || 'متوفر';
        } else {
            availBadge.className = 'badge badge-limited';
            availBadge.textContent = t.limitedStock || 'كمية محدودة';
        }
    }

    const mainImg = document.getElementById('modal-main-img');
    let imgSource = (product.images && product.images.length > 0 ? product.images[0] : null) || product.image || 'https://placehold.co/400x500/EBD7C9/8A2542text=No+Image';
    if (mainImg) mainImg.src = imgSource;

    const thumbnailsContainer = document.getElementById('modal-thumbnails');
    if (thumbnailsContainer) {
        thumbnailsContainer.innerHTML = '';
        let imagesArray = product.images && product.images.length > 0 ? product.images : [imgSource];
        if (imagesArray.length > 1) {
            imagesArray.forEach((imgUrl, idx) => {
                const thumb = document.createElement('img');
                thumb.src = imgUrl;
                thumb.style.objectFit = 'cover';
                if (idx === 0) thumb.classList.add('active');
                thumb.onclick = () => {
                    if (mainImg) mainImg.src = imgUrl;
                    document.querySelectorAll('.modal-thumbnails img').forEach(i => i.classList.remove('active'));
                    thumb.classList.add('active');
                };
                thumbnailsContainer.appendChild(thumb);
            });
        }
    }

    const waMessage = lang === 'ar' ? `السلام عليكم، أريد طلب موديل ${name}` 
        : `Merhaba, ${name} sipariş etmek istiyorum`;
    const waBtn = document.getElementById('modal-wa-btn');
    if (waBtn) {
        waBtn.innerHTML = t.orderModelWhatsapp || 'الطلب عبر واتساب';
        waBtn.href = `https://wa.me/905370498740text=${encodeURIComponent(waMessage)}`;
    }

    const modal = document.getElementById('product-modal');
    if (modal) {
        modal.classList.remove('hidden');
        document.body.style.overflow = 'hidden';
    }
};

